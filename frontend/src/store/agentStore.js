import { create } from 'zustand';

export const useAgentStore = create((set) => ({
  projectId: null,
  repoUrl: "",
  teamName: "",
  leaderName: "",
  runId: null,
  status: "idle", // "idle" | "running" | "passed" | "failed"
  thoughts: [],
  fixes: [],
  cicdRuns: [],
  score: { base: 100, speed_bonus: 0, efficiency_penalty: 0, total: 100 },
  healthScore: { before: 0, after: 0 },
  causalGraph: { nodes: [], edges: [] },
  whitebox: { enabled: true, status: 'PARTIAL', coverage: null, uncovered_paths: [], generated_tests: [], reason: 'White-box analysis not run.' },
  startTime: null,
  endTime: null,
  totalFailures: 0,
  totalFixes: 0,
  repositoryProfile: null,
  analysis: null,
  branch: "",
  push: null,
  
  // Actions
  setProjectId: (id) => set({ projectId: id }),
  setRepoUrl: (url) => set({ repoUrl: url }),
  setTeamName: (name) => set({ teamName: name }),
  setLeaderName: (name) => set({ leaderName: name }),
  setStatus: (status) => set({ status }),
  appendThought: (thought) => set((state) => ({ thoughts: [...state.thoughts, thought] })),
  appendFix: (fix) => set((state) => ({ fixes: [...state.fixes, fix] })),
  appendCicdRun: (run) => set((state) => ({ cicdRuns: [...state.cicdRuns, run] })),
  setScore: (score) => set({ score }),
  setHealthScore: (healthScore) => set({ healthScore }),
  setCausalGraph: (causalGraph) => set({ causalGraph }),
  setWhiteBox: (whitebox) => set({ whitebox }),
  setRunId: (runId) => set({ runId }),
  setStartTime: (startTime) => set({ startTime }),
  setEndTime: (endTime) => set({ endTime }),
  setTotals: (failures, fixes) => set({ totalFailures: failures, totalFixes: fixes }),
  setRepositoryProfile: (repositoryProfile) => set({ repositoryProfile }),
  setAnalysis: (analysis) => set({ analysis }),
  reset: () => set({
    runId: null,
    repoUrl: "",
    status: "idle",
    thoughts: [],
    fixes: [],
    cicdRuns: [],
    score: { base: 100, speed_bonus: 0, efficiency_penalty: 0, total: 100 },
    healthScore: { before: 0, after: 0 },
    causalGraph: { nodes: [], edges: [] },
    whitebox: { enabled: true, status: 'PARTIAL', coverage: null, uncovered_paths: [], generated_tests: [], reason: 'White-box analysis not run.' },
    startTime: null,
    endTime: null,
    totalFailures: 0,
    totalFixes: 0,
    repositoryProfile: null,
    analysis: null,
    branch: "",
    push: null,
  })
}));
